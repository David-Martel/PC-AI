#Requires -Version 7.0
<#
.SYNOPSIS
    Regenerates Tools/Quality/Data/PowerShellBuiltinCommands.txt, the static list of commands the
    quality ratchet treats as built-in when it looks for shadowing function definitions.

.DESCRIPTION
    The list is a committed artifact rather than a live Get-Command query so that the ratchet gives the
    same answer on every host (Get-Command output depends on PowerShell version, OS and installed
    modules). It is the sorted union of the cmdlets and functions exported by the modules that ship
    with PowerShell 7 ($PSHOME\Modules), with Windows PowerShell 5.1 and with the Windows inbox module
    set (System32\WindowsPowerShell\v1.0\Modules), plus the Microsoft.PowerShell.Core commands.
    Aliases are excluded. Re-run this script only when deliberately widening the list, and commit the
    result in its own reviewed change: a longer list can raise the shadowed-builtin-command count.

.EXAMPLE
    pwsh -NoProfile -File Tools/Quality/Update-PowerShellBuiltinCommandList.ps1
#>
[CmdletBinding()]
param(
    [string]$OutputPath = (Join-Path $PSScriptRoot 'Data/PowerShellBuiltinCommands.txt')
)

$ErrorActionPreference = 'Stop'

$collector = {
    $roots = @($PSHOME, (Join-Path $env:windir 'System32\WindowsPowerShell\v1.0')) |
        Where-Object { $_ -and (Test-Path -LiteralPath $_) } | ForEach-Object { (Resolve-Path -LiteralPath $_).Path }
    $names = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($command in (Get-Command -Module Microsoft.PowerShell.Core -CommandType Cmdlet, Function)) {
        [void]$names.Add($command.Name)
    }
    foreach ($module in (Get-Module -ListAvailable)) {
        $base = [string]$module.ModuleBase
        if (-not ($roots | Where-Object { $base.StartsWith($_, [StringComparison]::OrdinalIgnoreCase) })) { continue }
        foreach ($entry in $module.ExportedCommands.Values) {
            if ($entry.CommandType -in @('Cmdlet', 'Function')) { [void]$names.Add($entry.Name) }
        }
    }
    $names
}

$union = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
foreach ($name in (& $collector)) { [void]$union.Add($name) }

$winPs = Join-Path $env:windir 'System32\WindowsPowerShell\v1.0\powershell.exe'
if (Test-Path -LiteralPath $winPs) {
    $script51 = "`$ProgressPreference = 'SilentlyContinue'; & { $($collector.ToString()) } | ForEach-Object { `$_ }"
    $encoded = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($script51))
    $lines = & $winPs -NoProfile -NonInteractive -OutputFormat Text -EncodedCommand $encoded
    if ($LASTEXITCODE -ne 0) { throw "Windows PowerShell 5.1 enumeration failed with exit code $LASTEXITCODE" }
    foreach ($name in $lines) { if ($name -match '^\s*[A-Za-z][\w.-]*\s*$') { [void]$union.Add($name.Trim()) } }
}

$sorted = [string[]]$union
[Array]::Sort($sorted, [StringComparer]::OrdinalIgnoreCase)
$header = @(
    '# Built-in PowerShell command names (cmdlets and functions; no aliases), one per line.'
    '# Generated by Tools/Quality/Update-PowerShellBuiltinCommandList.ps1 - do not edit by hand.'
    "# Sources: PowerShell $($PSVersionTable.PSVersion) and Windows PowerShell 5.1 inbox modules. Entries: $($sorted.Count)"
)
$text = (($header + $sorted) -join "`n") + "`n"
[System.IO.File]::WriteAllText($OutputPath, $text, [System.Text.UTF8Encoding]::new($false))
"Wrote $($sorted.Count) names to $OutputPath"
